//! A catalog of named building blocks and gameplay objects.
//!
//! Scripts can use them three ways:
//!   block("spike", x, y)        by name
//!   obj(B_SPIKE, x, y)          by constant (every entry is available as B_<NAME>)
//!   rect(B_BASIC, x, y, 4, 3)   fill a grid of them
//!
//! IDs were checked against the GD Info Explorer object list. `gdl blocks` prints this table.

pub struct Block {
    pub name: &'static str,
    pub id: u32,
    pub category: &'static str,
}

const fn b(name: &'static str, id: u32, category: &'static str) -> Block {
    Block { name, id, category }
}

