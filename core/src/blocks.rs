pub fn find(name: &str) -> Option<&'static Block> {
    BLOCKS.iter().find(|b| b.name == name)
}

/// Plain-text table for `gdl blocks`.
pub fn table() -> String {
    let mut s = format!("{:<26} {:>5}  {}\n", "name (B_<NAME>)", "id", "category");
    for b in BLOCKS {
        s.push_str(&format!("{:<26} {:>5}  {}\n", b.name, b.id, b.category));
    }
    s
}

/// Generates `docs/BLOCKS.md`. A test keeps the committed file in sync with the table.
pub fn markdown() -> String {
    let mut s = String::from("# Block reference\n\n");
    s.push_str("<!-- Generated by `gdl docs blocks`. Do not edit by hand. -->\n\n");
    s.push_str(
        "Use a block three ways:\n\n```\nblock(\"spike\", 45, 15)        // by name\nobj(B_SPIKE, 45, 15)          // by constant (every name is also B_<NAME> in capitals)\nrect(B_BASIC, 15, 15, 4, 3)   // fill a 4x3 grid, 30 units apart\n```\n\n",
    );
    s.push_str("Not in the list? `obj(id, x, y)` takes any object id.\n");
    let mut cat = "";
    for b in BLOCKS {
        if b.category != cat {
            cat = b.category;
            s.push_str(&format!("\n## {cat}\n\n| name | constant | id |\n|---|---|---|\n"));
        }
        s.push_str(&format!("| `{}` | `B_{}` | {} |\n", b.name, b.name.to_uppercase(), b.id));
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn committed_docs_match_the_table() {
        assert_eq!(
            include_str!("../../docs/BLOCKS.md"),
            markdown(),
            "docs/BLOCKS.md is out of date: run `cargo run -p gdl -- docs blocks > docs/BLOCKS.md`"
        );
    }

    #[test]
    fn names_and_ids_are_unique() {
        for (i, a) in BLOCKS.iter().enumerate() {
            for o in &BLOCKS[..i] {
                assert_ne!(a.name, o.name, "duplicate name");
                assert_ne!(a.id, o.id, "duplicate id {} ({} / {})", a.id, a.name, o.name);
            }
        }
    }
}
